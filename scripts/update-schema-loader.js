#!/usr/bin/env node
'use strict';

const { readdirSync, writeFileSync, readFileSync } = require('fs');
const { join } = require('path');

const schemasDir = join(__dirname, '..', 'src', 'shared', 'provider-schemas');
const loaderPath = join(__dirname, '..', 'src', 'shared', 'schema-loader.ts');
const versionsPath = join(__dirname, '..', 'src', 'shared', 'versions.ts');

const versions = readdirSync(schemasDir)
  .filter(f => f.endsWith('.json'))
  .map(f => f.replace('.json', ''))
  .sort((a, b) => {
    const [aMaj, aMin, aPat] = a.split('.').map(Number);
    const [bMaj, bMin, bPat] = b.split('.').map(Number);
    return aMaj - bMaj || aMin - bMin || aPat - bPat;
  });

if (versions.length === 0) {
  console.error('No schema JSON files found in', schemasDir);
  process.exit(1);
}

const importLines = versions.map(v => {
  const varName = 'schema_raw_' + v.replace(/\./g, '_');
  return `import ${varName} from './provider-schemas/${v}.json';`;
}).join('\n');

const schemaEntries = versions.map(v => {
  const varName = 'schema_raw_' + v.replace(/\./g, '_');
  return `  '${v}': ${varName} as unknown as ProviderSchema,`;
}).join('\n');

const loaderContent = `// AUTO-GENERATED by scripts/update-schema-loader.js — do not edit manually.
// To regenerate: node scripts/update-schema-loader.js
import type { ProviderSchema, ResourceSchema } from './provider-schemas/schema-types';

${importLines}

const SCHEMAS: Record<string, ProviderSchema> = {
${schemaEntries}
};

export function loadSchema(version: string): ProviderSchema {
  const schema = SCHEMAS[version];
  if (!schema) throw new Error(\`No schema snapshot for provider version \${version}\`);
  return schema;
}

export function getResourceSchema(version: string, resourceType: string): ResourceSchema | null {
  const schema = loadSchema(version);
  return (schema.resource_schemas[resourceType] ?? schema.data_source_schemas[resourceType]) ?? null;
}

export function isKnownResource(version: string, resourceType: string): boolean {
  const schema = loadSchema(version);
  return resourceType in schema.resource_schemas || resourceType in schema.data_source_schemas;
}
`;

writeFileSync(loaderPath, loaderContent);
console.log(`✓ schema-loader.ts updated with ${versions.length} versions: ${versions.join(', ')}`);

let versionsContent = readFileSync(versionsPath, 'utf-8');

// Extract existing versions from SUPPORTED_VERSIONS to preserve the full union type.
// versions.ts uses Record<ProviderVersion, ...> for VERSION_RESOURCE_ADDITIONS and
// VERSION_ATTRIBUTE_NOTES — removing keys from the union causes compile errors until
// all schema JSON files exist (Task 5). Merge instead of replace.
const existingMatch = versionsContent.match(
  /export const SUPPORTED_VERSIONS = \[(.*?)\] as const;/
);
const existingVersions = existingMatch
  ? existingMatch[1].match(/'([^']+)'/g)?.map(s => s.replace(/'/g, '')) ?? []
  : [];

const allVersions = Array.from(new Set([...existingVersions, ...versions])).sort((a, b) => {
  const [aMaj, aMin, aPat] = a.split('.').map(Number);
  const [bMaj, bMin, bPat] = b.split('.').map(Number);
  return aMaj - bMaj || aMin - bMin || aPat - bPat;
});

const newVersionsLine = `export const SUPPORTED_VERSIONS = [${allVersions.map(v => `'${v}'`).join(', ')}] as const;`;
versionsContent = versionsContent.replace(
  /export const SUPPORTED_VERSIONS = \[.*?\] as const;/,
  newVersionsLine
);
// Add empty entries for new versions in VERSION_RESOURCE_ADDITIONS and VERSION_ATTRIBUTE_NOTES.
// Both are Record<ProviderVersion, ...> so every version in the union needs an entry.
const newVersions = allVersions.filter(v => !existingVersions.includes(v));
for (const v of newVersions) {
  // Insert `  'X.X.X': [],` before the closing `};` of each record.
  versionsContent = versionsContent
    .replace(
      /(export const VERSION_RESOURCE_ADDITIONS[\s\S]*?)(};)/,
      (_, body, close) => `${body}  '${v}': [],\n\n${close}`
    )
    .replace(
      /(export const VERSION_ATTRIBUTE_NOTES[\s\S]*?)(};)/,
      (_, body, close) => `${body}  '${v}': [],\n${close}`
    );
  console.log(`✓ Added empty '${v}' entries to VERSION_RESOURCE_ADDITIONS and VERSION_ATTRIBUTE_NOTES`);
}

// Advance DEFAULT_VERSION to the newest schema-backed version.
const newestVersion = versions[versions.length - 1];
versionsContent = versionsContent.replace(
  /export const DEFAULT_VERSION: ProviderVersion = '[^']+';/,
  `export const DEFAULT_VERSION: ProviderVersion = '${newestVersion}';`
);
console.log(`✓ DEFAULT_VERSION advanced to ${newestVersion}`);

writeFileSync(versionsPath, versionsContent);
console.log(`✓ SUPPORTED_VERSIONS updated in versions.ts (${allVersions.length} versions, ${versions.length} schema-backed)`);
